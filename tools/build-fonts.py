#!/usr/bin/env python3
"""Self-hosted fonts: downloads the site's font files from Google Fonts once and writes /fonts.css that points to them,
so no page needs fonts.googleapis.com / fonts.gstatic.com at all.

    python tools/build-fonts.py            (needs internet; writes fonts/*.woff2 and fonts.css; safe to re-run)

Families (same as the home page used): Jost 300-500, IBM Plex Sans Arabic 300-700, Cormorant Garamond 500-700, Montserrat 300-700.
Subsets kept: latin, latin-ext, arabic, cyrillic (the site's seven languages). Others (vietnamese, cyrillic-ext) are skipped."""
import os, re, sys, urllib.request, hashlib
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "fonts"); os.makedirs(OUT, exist_ok=True)
KEEP = {"latin", "latin-ext", "arabic", "cyrillic"}
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"
CSS_URL = ("https://fonts.googleapis.com/css2?family=Jost:wght@300;400;500&family=IBM+Plex+Sans+Arabic:wght@300;400;500;600;700"
           "&family=Cormorant+Garamond:wght@500;600;700&family=Montserrat:wght@300;400;500;600;700&display=swap")
def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()
css = get(CSS_URL).decode("utf-8")
blocks = re.findall(r"/\* ([a-z-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
out, files, seen = [], {}, {}
for subset, block in blocks:
    if subset not in KEEP: continue
    fam = re.search(r"font-family: '([^']+)'", block).group(1)
    wt = re.search(r"font-weight: ([\d ]+);", block).group(1)
    url = re.search(r"url\(([^)]+)\)", block).group(1)
    if url not in files:
        name = "%s-%s-%s.woff2" % (fam.lower().replace(" ", "-"), subset, hashlib.md5(url.encode()).hexdigest()[:6])
        data = get(url); open(os.path.join(OUT, name), "wb").write(data); files[url] = (name, len(data))
    name = files[url][0]
    rng = re.search(r"unicode-range: ([^;]+);", block).group(1)
    out.append("@font-face{font-family:'%s';font-style:normal;font-weight:%s;font-display:swap;src:url(/fonts/%s) format('woff2');unicode-range:%s}" % (fam, wt, name, rng))
header = "/* Generated by tools/build-fonts.py - self-hosted Jost, IBM Plex Sans Arabic, Cormorant Garamond, Montserrat (latin, latin-ext, arabic, cyrillic). */\n"
open(os.path.join(ROOT, "fonts.css"), "w", encoding="utf-8", newline="\n").write(header + "\n".join(out) + "\n")
tot = sum(v[1] for v in files.values())
print("faces:", len(out), "| files:", len(files), "| total %.0f KB" % (tot / 1024))
for u, (n, sz) in sorted(files.items(), key=lambda x: x[1][0]): print("  %-52s %5.1f KB" % (n, sz / 1024))
