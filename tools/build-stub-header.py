#!/usr/bin/env python3
"""
Builds the header that the language product pages (/ar|de|es|it|fr|ru/product/...) get from site-nav.js.
Those pages are small SEO pages with a plain text header. This copies the real header (logo, menu, search,
language, currency, favourites, bag, account) and the CSS it needs from offers/index.html, so every page has the
same header, and writes it into site-nav.js between the stub-header markers. Re-run after the header changes:

    python tools/build-stub-header.py
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "offers", "index.html")
NAV = os.path.join(ROOT, "site-nav.js")
BEGIN, END = "// ---- stub header (generated by tools/build-stub-header.py)", "// ---- end stub header"

page = open(SRC, encoding="utf-8").read()
css = re.search(r"<style data-shell>(.*?)</style>", page, re.S).group(1)
hd = re.search(r"<header id=\"hd\">.*?</header>", page, re.S).group(0)

# header markup: no announcement bar, a div (the stub pages style the <header> tag), logo etc. as on the other pages
hd = re.sub(r"<div class=\"bar\" id=\"bar\">.*?</script>\n?", "", hd, flags=re.S)
hd = hd.replace('<header id="hd">', '<div id="hd" role="banner">').replace("</header>", "</div>")

# split the CSS into top-level rules (a rule or a whole @media block), keep what the header uses
def blocks(s):
    out, i, n = [], 0, len(s)
    while i < n:
        j = s.find("{", i)
        if j < 0: break
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(s[k], 0); k += 1
        out.append((s[i:j].strip(), s[j + 1:k - 1], s[i:k].strip()))
        i = k
    return out

KEEP = re.compile(r"(^:root$|#hd\b|\.bar\b|\.row\b|\.pill\b|(^|[\s,>+~])nav\b|\.ib\b|\.cnt\b|\.logo\b|\.mega\b|\.mg\b|\.ml\b|\.mu\b|\.mt\b|\.tl\b|\.tg\b|\.ti\b|\.ph\b|\.mcol\b|\.srch\b|\.sgs\b|\.pop\b|#sr\b|#si\b|#sgs\b|#wcb\b|#cc\b|#wc\b|#lgp\b|#cpop\b|#pop\b|#blg\b|#bcur\b|#bs\b|#bfv\b|#bb\b|#ba\b|#bt\b|#mbt\b|svg\.i\b|\.mb\b|light-page|\.hl\b)")

def scope(sel):
    parts = []
    for p in sel.split(","):
        p = p.strip()
        parts.append("#hd " + p if re.match(r"nav\b", p) else p)
    return ",".join(parts)

def keep_rules(body):
    res = []
    for sel, inner, whole in blocks(body):
        if sel.startswith("@"):
            continue
        if KEEP.search(sel) and not re.search(r"\.hero\b|\.hbg\b|\.hs\b", sel):
            res.append(scope(sel) + "{" + inner + "}")
    return res

kept = []
# Every <style> block of the page, in page order (later blocks override earlier ones): the cascade is kept the same by
# keeping the LAST copy of any rule that repeats.
allcss = "".join(m.group(1) for m in re.finditer(r"<style[^>]*>(.*?)</style>", page, re.S))
allcss = re.sub(r"/\*.*?\*/", "", allcss, flags=re.S)
for sel, inner, whole in blocks(allcss):
    if sel.startswith("@media"):
        r = keep_rules(inner)
        if r: kept.append(sel + "{" + "".join(r) + "}")
    elif sel.startswith("@keyframes"):
        if sel.endswith(" ck"): kept.append(whole)
    elif sel.startswith("@"):
        continue
    elif KEEP.search(sel) and not re.search(r"\.hero\b|\.hbg\b|\.hs\b", sel):
        kept.append(scope(sel) + "{" + inner + "}")
def dedupe(rules):
    seen, out = set(), []
    for r in reversed(rules):
        if r in seen: continue
        seen.add(r); out.append(r)
    return list(reversed(out))
kept = [k.replace("header#hd", "#hd") for k in dedupe(kept)]
extra = ("#hd{line-height:normal;font-family:Jost,sans-serif;font-weight:300}#hd button,#hd input{font:inherit;color:inherit}#hd button{background:none;border:0;cursor:pointer}"
         "@media (min-width:1181px){#hd .row{grid-template-columns:auto minmax(0,1fr) auto}#hd nav a,#hd nav button{padding:0 9px;text-align:center;line-height:1.15}}@media (min-width:1181px) and (max-width:1320px){#hd nav a,#hd nav button{font-size:15px;padding:0 6px}}"
         "#hd a{color:inherit;text-decoration:none;font-weight:inherit}#hd ul,#hd li{margin:0;padding:0;list-style:none}")
CSS = "".join(kept) + extra

# footer (same markup and CSS as the other pages) for the small service pages that have none
cpage = open(os.path.join(ROOT, "contact", "index.html"), encoding="utf-8").read()
FOOT = re.search(r"<footer class=\"ftr\">.*?</footer>", cpage, re.S).group(0)
FKEEP = re.compile(r"(\.ftr|\.soc-ic|footer\.ftr)")
fcss_all = re.sub(r"/\*.*?\*/", "", "".join(m.group(1) for m in re.finditer(r"<style[^>]*>(.*?)</style>", cpage, re.S)), flags=re.S)
fk = []
for sel, inner, whole in blocks(fcss_all):
    if sel.startswith("@media"):
        r = ["%s{%s}" % (s2, i2) for s2, i2, w2 in blocks(inner) if not s2.startswith("@") and FKEEP.search(s2)]
        if r: fk.append(sel + "{" + "".join(r) + "}")
    elif not sel.startswith("@") and FKEEP.search(sel):
        fk.append(sel + "{" + inner + "}")
FCSS = "".join(dedupe(fk))

nav = open(NAV, encoding="utf-8").read()
mm = json.loads(re.search(r"MM_I18N = (\{.*?\});", nav, re.S).group(1))
KEYS = ["Home", "All Shop", "Sunglasses", "Optical", "Brands", "Services", "Blog", "Offers"]
I18N = {}
for lang in ["ar", "de", "es", "it", "fr", "ru"]:
    d = mm.get(lang, {})
    I18N[lang] = {k: d[k] for k in KEYS if k in d}
    I18N[lang]["Visit Us"] = d.get("Book a visit", "Visit Us")
PH = {"en": "Search brands and models", "ar": "ابحث عن علامة أو موديل", "de": "Marken und Modelle suchen", "es": "Buscar marcas y modelos",
      "it": "Cerca marchi e modelli", "fr": "Rechercher marques et modèles", "ru": "Поиск брендов и моделей"}
LG = {"en": "EN", "ar": "ع", "de": "DE", "es": "ES", "it": "IT", "fr": "FR", "ru": "RU"}

code = BEGIN + """
// The language product pages have a plain text header. Here they get the real one (the same markup and CSS as the other pages),
// before the menu and header code below run, so the menu, search, language, currency and the drawers all work on them too.
(function () {
  if (document.getElementById('hd') || !/^\\/((ar|de|es|it|fr|ru)\\/product\\/|(hotel-pickup|eye-examination|try-on-frames|frame-consultation|policies)\\/?(index\\.html)?$)/.test(location.pathname)) return;
  var old = document.querySelector('body > header'); if (!old) return;
  var L = 'en'; try { L = localStorage.seenLang || document.documentElement.getAttribute('lang') || 'en'; } catch (e) {}
  var T = %s, PH = %s, LG = %s, t = T[L] || {};
  var st = document.createElement('style'); st.id = 'stubHdCss'; st.textContent = %s; document.head.appendChild(st);
  var box = document.createElement('div'); box.innerHTML = %s;
  var hd = box.firstChild; old.parentNode.replaceChild(hd, old);
  [].forEach.call(hd.querySelectorAll('#nav > *'), function (el) {
    var n = el.firstChild; if (n && n.nodeType === 3 && t[n.nodeValue.trim()]) n.nodeValue = t[n.nodeValue.trim()];
  });
  var si = hd.querySelector('#si'); if (si) { si.placeholder = PH[L] || PH.en; si.setAttribute('aria-label', PH[L] || PH.en); }
  var bl = hd.querySelector('#blg'); if (bl) bl.textContent = LG[L] || 'EN';
  var cu = hd.querySelector('#bcur'); try { if (cu && localStorage.seenCur) cu.textContent = localStorage.seenCur; } catch (e) {}
  document.body.style.paddingTop = '82px';
})();
// The small service pages (hotel pick-up, eye examination, try-on, consultation, policies) also get the footer.
(function () {
  if (!/^\\/(hotel-pickup|eye-examination|try-on-frames|frame-consultation|policies)\\/?(index\\.html)?$/.test(location.pathname)) return;
  var oldf = document.querySelector('body > footer'); if (document.querySelector('footer.ftr')) return;
  var st = document.createElement('style'); st.id = 'stubFtCss'; st.textContent = %s; document.head.appendChild(st);
  var box = document.createElement('div'); box.innerHTML = %s;
  var f = box.firstChild;
  if (oldf) oldf.parentNode.replaceChild(f, oldf); else document.body.appendChild(f);
})();
""" % (json.dumps(I18N, ensure_ascii=False), json.dumps(PH, ensure_ascii=False), json.dumps(LG, ensure_ascii=False), json.dumps(CSS), json.dumps(hd), json.dumps(FCSS), json.dumps(FOOT)) + END + "\n"

if BEGIN in nav:
    nav = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda m: code, nav, flags=re.S)
else:
    i = nav.index("(function () {")
    nav = nav[:i] + code + nav[i:]
open(NAV, "w", encoding="utf-8", newline="").write(nav)
print("css bytes", len(CSS), "header bytes", len(hd), "site-nav.js bytes", len(nav))